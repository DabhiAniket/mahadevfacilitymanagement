export function visualById(id: string): Visual {
  const v = visuals.find((x) => x.id === id);
  if (!v) throw new Error(`Unknown visual "${id}" in src/data/visuals.ts`);
  return v;
}

export function srcFor(v: Visual, width: number, format: "avif" | "webp") {
  return `${v.file}-${width}.${format}`;
}
