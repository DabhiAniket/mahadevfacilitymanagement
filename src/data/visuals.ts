/** Camera framing for one end of a beat: zoom (1 = cover fit) and focal point offset. */
export type Frame = { zoom: number; dx: number; dy: number };

type Beat = {
  /** Spacer id; also the in-page anchor. */
  id: string;
  visual: Visual["id"];
  /** Framing at the start and end of the beat; the camera dollies between them with scroll. */
  from: Frame;
  to: Frame;
  /** Caption for visual-only beats (null when the beat has its own copy). */
  caption: string | null;
};

