// `npm run visuals` to regenerate the web files.
//
// Plain, erasable TypeScript only (no enums, no path aliases): the build-time
// permission check (scripts/check-visual-permissions.mjs) imports this file
// directly with Node.

type PermissionStatus = "pending" | "granted";

/** Crop focal point as fractions of the image (0..1), like object-position. */
type Focal = { x: number; y: number };

export type Visual = {
  id: string;
  /** Public path without size or extension; files are `${file}-${width}.avif|webp`. */
  file: string;
  /** Original file in assets/source (not served). */
  sourceFile: string;
  sourceUrl: string;
  width: number;
  height: number;
  /** Widths generated by `npm run visuals` (largest is used on desktop). */
  widths: number[];
  alt: string;
  /** Shown on the site only once permission is granted, e.g. "Photo: ...". */
  credit: string | null;
  permissionStatus: PermissionStatus;
  /** Who granted permission and when, once granted. */
  permissionGrantedBy: string | null;
  permissionDate: string | null;
  /** Crop for landscape frames (desktop) and portrait/near-square frames (phones). */
  focal: { wide: Focal; tall: Focal };
};

